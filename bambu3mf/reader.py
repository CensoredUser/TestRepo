"""Read Bambu Studio (and plain) 3MF files.

``read_project`` turns a Bambu Studio project into a :class:`Project` that can
be modified and written back with :func:`bambu3mf.writer.write_3mf`.
Painting data (per-triangle ``paint_*`` attributes), custom per-layer G-code,
variable layer heights and other auxiliary files are carried over unchanged.
"""

from __future__ import annotations

import json
import re
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from .mesh import Matrix, Mesh, apply, identity, matmul, parse_3mf_transform, translation
from .project import Bed, Instance, LayerRange, Metadata, ModelObject, Part, Plate, Project

CORE = "http://schemas.microsoft.com/3dmanufacturing/core/2015/02"
PROD = "http://schemas.microsoft.com/3dmanufacturing/production/2015/06"
RELS = "http://schemas.openxmlformats.org/package/2006/relationships"
_Q = lambda tag: f"{{{CORE}}}{tag}"

# Files regenerated by the writer or invalidated by edits (sliced G-code etc.).
_REGENERATED = re.compile(
    r"^(\[Content_Types\]\.xml|_rels/\.rels|3D/.*|Metadata/(project_settings\.config|model_settings\.config|"
    r"layer_config_ranges\.xml|slice_info\.config|cut_information\.xml|_rels/.*|"
    r"(plate|plate_no_light|top|pick)_\d+(_small)?\.(png|json)|plate_\d+\.gcode(\.md5)?|"
    r"plate_\d+\.json|print_profile\.config|(process|filament|machine)_settings_\d+\.config))$", re.I)
_EMBEDDED_RE = re.compile(r"^Metadata/(process|filament|machine)_settings_(\d+)\.config$", re.I)
_EMBEDDED_ID = {"process": "print_settings_id", "filament": "filament_settings_id", "machine": "printer_settings_id"}


class _MeshObj:
    def __init__(self):
        self.vertices: List[Tuple[float, float, float]] = []
        self.triangles: List[Tuple[int, int, int]] = []
        self.attrs: List[dict] = []
        self.components: List[Tuple[Optional[str], int, Matrix]] = []
        self.type = "model"


def _parse_model(data: bytes) -> Tuple[Dict[int, _MeshObj], List[Tuple[int, Matrix, bool, Optional[str]]], Dict[str, str]]:
    root = ET.fromstring(data)
    objects: Dict[int, _MeshObj] = {}
    metadata = {}
    for md in root.findall(_Q("metadata")):
        metadata[md.get("name", "")] = md.text or ""
    res = root.find(_Q("resources"))
    for obj in (res.findall(_Q("object")) if res is not None else []):
        mo = _MeshObj()
        mo.type = obj.get("type", "model")
        mesh = obj.find(_Q("mesh"))
        if mesh is not None:
            verts = mesh.find(_Q("vertices"))
            for v in (verts if verts is not None else []):
                mo.vertices.append((float(v.get("x")), float(v.get("y")), float(v.get("z"))))
            tris = mesh.find(_Q("triangles"))
            for t in (tris if tris is not None else []):
                mo.triangles.append((int(t.get("v1")), int(t.get("v2")), int(t.get("v3"))))
                extra = {k: v for k, v in t.attrib.items() if k not in ("v1", "v2", "v3")}
                mo.attrs.append(extra)
        comps = obj.find(_Q("components"))
        for c in (comps if comps is not None else []):
            path = c.get(f"{{{PROD}}}path")
            tr = c.get("transform")
            mo.components.append((path, int(c.get("objectid")), parse_3mf_transform(tr) if tr else identity()))
        objects[int(obj.get("id"))] = mo
    items = []
    build = root.find(_Q("build"))
    for it in (build if build is not None else []):
        tr = it.get("transform")
        items.append((int(it.get("objectid")), parse_3mf_transform(tr) if tr else identity(),
                      it.get("printable", "1") != "0", it.get(f"{{{PROD}}}path")))
    return objects, items, metadata


class _Archive:
    def __init__(self, path):
        self.zip = zipfile.ZipFile(path)
        self.names = {n.replace("\\", "/"): n for n in self.zip.namelist()}
        self._models: Dict[str, Tuple] = {}
        start = "3D/3dmodel.model"
        if "_rels/.rels" in self.names:
            rels = ET.fromstring(self.zip.read(self.names["_rels/.rels"]))
            for r in rels:
                if r.get("Type", "").endswith("/3dmodel"):
                    start = r.get("Target", start).lstrip("/")
        self.start = start

    def read(self, name: str) -> Optional[bytes]:
        n = self.names.get(name.lstrip("/"))
        return self.zip.read(n) if n else None

    def model(self, path: Optional[str]):
        key = (path or self.start).lstrip("/")
        if key not in self._models:
            data = self.read(key)
            if data is None:
                raise ValueError(f"3MF part {key} is missing")
            self._models[key] = _parse_model(data)
        return self._models[key]

    def volumes(self, path: Optional[str], oid: int, tr: Matrix, depth=0):
        """Flatten an object into [(mesh_obj, transform, volume_id)]."""
        if depth > 16:
            raise ValueError("component nesting too deep")
        objects = self.model(path)[0]
        mo = objects.get(oid)
        if mo is None:
            raise ValueError(f"object {oid} missing in {path or self.start}")
        out = []
        if mo.vertices:
            out.append((mo, tr, oid))
        for cpath, cid, ctr in mo.components:
            out += self.volumes(cpath or path, cid, matmul(tr, ctr), depth + 1)
        return out


def _mesh_from(mo: _MeshObj, tr: Matrix) -> Mesh:
    attrs = mo.attrs if any(mo.attrs) else None
    return Mesh(list(mo.vertices), list(mo.triangles), "", [dict(a) for a in attrs] if attrs else None).transformed(tr)


def read_meshes(path) -> List[Mesh]:
    """All printable meshes of a (any-vendor) 3MF, in build (world) coordinates."""
    ar = _Archive(path)
    _, items, _ = ar.model(None)
    out = []
    for oid, tr, _printable, ipath in items:
        for mo, vtr, _ in ar.volumes(ipath, oid, tr):
            if mo.type in ("model", "solidsupport") or mo.type == "":
                out.append(_mesh_from(mo, vtr))
    return out


def _parse_model_settings(data: Optional[bytes]):
    objects: Dict[int, dict] = {}
    plates: List[dict] = []
    if not data:
        return objects, plates
    root = ET.fromstring(data)
    for o in root.findall("object"):
        info = {"name": "", "settings": {}, "parts": {}}
        for md in o.findall("metadata"):
            k, v = md.get("key"), md.get("value", "")
            if k == "name":
                info["name"] = v
            elif k and k not in ("module",):
                info["settings"][k] = v
        for p in o.findall("part"):
            pinfo = {"subtype": p.get("subtype", "normal_part"), "name": "", "settings": {}, "source": ""}
            for md in p.findall("metadata"):
                k, v = md.get("key"), md.get("value", "")
                if k == "name":
                    pinfo["name"] = v
                elif k == "source_file":
                    pinfo["source"] = v
                elif k in ("matrix", "source_object_id", "source_volume_id", "source_offset_x",
                           "source_offset_y", "source_offset_z", "source_in_inches", "source_in_meters"):
                    continue
                elif k:
                    pinfo["settings"][k] = v
            info["parts"][int(p.get("id"))] = pinfo
        objects[int(o.get("id"))] = info
    for pl in root.findall("plate"):
        pinfo = {"meta": {}, "instances": []}
        for md in pl.findall("metadata"):
            pinfo["meta"][md.get("key")] = md.get("value", "")
        for mi in pl.findall("model_instance"):
            vals = {md.get("key"): md.get("value") for md in mi.findall("metadata")}
            pinfo["instances"].append((int(vals.get("object_id", -1)), int(vals.get("instance_id", 0))))
        plates.append(pinfo)
    return objects, plates


def _parse_layer_ranges(data: Optional[bytes]) -> Dict[int, List[LayerRange]]:
    out: Dict[int, List[LayerRange]] = {}
    if not data:
        return out
    root = ET.fromstring(data)
    for o in root.findall("object"):
        ranges = []
        for r in o.findall("range"):
            settings = {op.get("opt_key"): (op.text or "") for op in r.findall("option")}
            ranges.append(LayerRange(float(r.get("min_z")), float(r.get("max_z")), settings))
        out[int(o.get("id"))] = ranges
    return out


def _linear_key(m: Matrix) -> Tuple:
    return tuple(round(m[r][c], 9) for r in range(3) for c in range(3))


def read_project(path) -> Project:
    """Load a Bambu Studio project 3MF (geometry, settings, plates)."""
    ar = _Archive(path)
    _, items, metadata = ar.model(None)
    cfg_data = ar.read("Metadata/project_settings.config")
    config = json.loads(cfg_data.decode("utf-8")) if cfg_data else {}
    project = Project(config)
    app = metadata.get("Application", "")
    if app.startswith("BambuStudio-"):
        project.app_version = app[len("BambuStudio-"):]
    md = Metadata(title=metadata.get("Title", ""), designer=metadata.get("Designer", ""),
                  description=metadata.get("Description", ""),
                  copyright=metadata.get("Copyright", metadata.get("CopyRight", "")),
                  license=metadata.get("License", ""), origin=metadata.get("Origin", ""))
    project.metadata = md
    obj_info, plate_info = _parse_model_settings(ar.read("Metadata/model_settings.config"))
    ranges = _parse_layer_ranges(ar.read("Metadata/layer_config_ranges.xml"))

    # plates
    if plate_info:
        project.plates = []
        for p in plate_info:
            m = p["meta"]
            sm = m.get("spiral_mode")
            project.plates.append(Plate(name=m.get("plater_name", ""), locked=m.get("locked") == "true",
                                        bed_type=m.get("bed_type") or None,
                                        print_sequence=m.get("print_sequence") or None,
                                        spiral_mode=(sm in ("1", "true")) if sm is not None else None))
    inst_plate: Dict[Tuple[int, int], int] = {}
    for pi, p in enumerate(plate_info):
        for oid, iid in p["instances"]:
            inst_plate[(oid, iid)] = pi

    # group build items by object id (first appearance order = Bambu model object order)
    order: List[int] = []
    grouped: Dict[int, List[Tuple[Matrix, bool, Optional[str]]]] = {}
    for oid, tr, printable, ipath in items:
        if oid not in grouped:
            order.append(oid)
            grouped[oid] = []
        grouped[oid].append((tr, printable, ipath))

    bed = project.bed
    nplates = len(project.plates)
    for model_index, oid in enumerate(order, start=1):
        info = obj_info.get(oid, {"name": f"Object {model_index}", "settings": {}, "parts": {}})
        insts = grouped[oid]
        # Bambu stores per-instance rotation/scale in the build item; objects here keep
        # one shared transform, so instances with different rotations become separate objects.
        by_linear: Dict[Tuple, List[Tuple[int, Matrix, bool]]] = {}
        for iid, (tr, printable, _ipath) in enumerate(insts):
            by_linear.setdefault(_linear_key(tr), []).append((iid, tr, printable))
        vols = ar.volumes(insts[0][2], oid, identity())
        for group in by_linear.values():
            lin = [row[:] for row in group[0][1]]
            lin[0][3] = lin[1][3] = lin[2][3] = 0.0
            parts = []
            for mo, vtr, vid in vols:
                pinfo = info["parts"].get(vid, {})
                settings = dict(pinfo.get("settings", {}))
                extruder = settings.pop("extruder", None)
                mesh = _mesh_from(mo, vtr)
                mesh.source = pinfo.get("source", "")
                parts.append(Part(mesh=mesh, name=pinfo.get("name", ""),
                                  subtype=pinfo.get("subtype", "normal_part" if mo.type == "model" else "modifier_part"),
                                  settings=settings, extruder=int(extruder) if extruder else None))
            osettings = dict(info.get("settings", {}))
            extruder = int(osettings.pop("extruder", "1") or 1)
            obj = ModelObject(name=info.get("name") or f"Object {model_index}", parts=parts, transform=lin,
                              settings=osettings, extruder=extruder, instances=[],
                              layer_ranges=list(ranges.get(model_index, [])))
            lo, hi = obj.bounds()
            c = tuple((lo[i] + hi[i]) / 2 for i in range(3))
            for iid, tr, printable in group:
                wx, wy = tr[0][3] + c[0], tr[1][3] + c[1]
                pi = inst_plate.get((oid, iid))
                if pi is None:
                    pi = _plate_at(bed, wx, wy, nplates)
                ox, oy = bed.plate_origin(pi, nplates)
                floor = tr[2][3] + lo[2]
                if abs(floor) > 0.01:
                    project.warnings.append(f"'{obj.name}' was {floor:+.2f} mm off the bed; it is placed on the bed")
                obj.instances.append(Instance(x=wx - ox, y=wy - oy, printable=printable, placed=True, plate=pi))
            obj.plate = obj.instances[0].plate or 0
            project.objects.append(obj)
            if len(by_linear) > 1:
                project.warnings.append(f"'{obj.name}': instances with different rotations were split into "
                                        "separate objects")
    while len(project.plates) < max([1] + [i.plate + 1 for o in project.objects for i in o.instances if i.plate is not None]):
        project.plates.append(Plate())

    embedded = []
    for name in ar.names:
        m = _EMBEDDED_RE.match(name)
        if m:
            try:
                cfg = json.loads(ar.zip.read(ar.names[name]).decode("utf-8"))
            except ValueError:
                project.warnings.append(f"{name}: not valid JSON, dropped")
                continue
            kind = m.group(1).lower()
            pid = cfg.get(_EMBEDDED_ID[kind])
            pname = (pid[0] if isinstance(pid, list) and pid else pid) or cfg.get("name", "")
            embedded.append((kind, int(m.group(2)), {"type": kind, "name": pname, "config": cfg}))
        elif not _REGENERATED.match(name):
            project.extra_files[name] = ar.zip.read(ar.names[name])
    order = {"process": 0, "filament": 1, "machine": 2}
    project.embedded_presets = [e for _, _, e in sorted(embedded, key=lambda t: (order[t[0]], t[1]))]
    return project


def _plate_at(bed: Bed, x: float, y: float, nplates: int) -> int:
    for i in range(max(nplates, 1)):
        ox, oy = bed.plate_origin(i, nplates)
        if ox + bed.min_x - 1 <= x <= ox + bed.max_x + 1 and oy + bed.min_y - 1 <= y <= oy + bed.max_y + 1:
            return i
    return 0
